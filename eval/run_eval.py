"""
eval/run_eval.py
─────────────────────────────────────────────────────────────────────────────
Extraction benchmark: run the real PDF → text → Gemini pipeline on every
synthetic statement in eval/statements/ and score it against ground truth.

Only spending (debit) rows are scored. The parser deliberately skips bill
payments and cashback credits, since the utilization score is built on spend.

    GEMINI_API_KEY=... python -m eval.run_eval [--runs 3]

Writes eval/RESULTS.md (summary and per-statement tables, every error) and
eval/predictions/<statement>.json (the raw parsed transactions).
─────────────────────────────────────────────────────────────────────────────
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
import time
from datetime import UTC, datetime
from pathlib import Path

from dotenv import load_dotenv

from agents.parse_node import _parse_transactions_from_text
from agents.pdf_node import _decrypt_pdf, _extract_text
from eval.scoring import StatementScore, score_statement, summarise

EVAL_DIR = Path(__file__).parent
STATEMENTS = EVAL_DIR / "statements"
PREDICTIONS = EVAL_DIR / "predictions"
MODEL = "gemini-2.5-flash"


def parse_statement(pdf_path: Path, truth: dict) -> list[dict]:
    """The same steps the API runs: decrypt, extract text, parse with Gemini."""
    pdf_bytes, _ = _decrypt_pdf(pdf_path.read_bytes(), truth.get("password"))
    month = truth["transactions"][0]["date"][:7]
    text = _extract_text(pdf_bytes, month)
    return [dict(t) for t in _parse_transactions_from_text(text, month)]


def pct(x: float) -> str:
    return f"{x * 100:.1f}%"


def write_report(runs: list[list[StatementScore]], banks: dict[str, str], seconds: float) -> str:
    all_scores = [s for run in runs for s in run]
    total = summarise(all_scores)
    n_statements = len(runs[0])
    lines = [
        "# Extraction benchmark results",
        "",
        f"Run on {datetime.now(UTC):%Y-%m-%d} with `{MODEL}` (temperature 0, JSON mode) over "
        f"{n_statements} synthetic statements from {len(set(banks.values()))} banks, "
        f"{total['true_rows'] // len(runs)} spending transactions, repeated {len(runs)} times "
        f"({total['true_rows']} scored rows). Generated by `python -m eval.run_eval --runs {len(runs)}` "
        f"in {seconds / 60:.0f} min.",
        "",
        "Only spending (debit) rows are scored: the parser deliberately skips bill payments and "
        "cashback credits, because the utilization score is built on spend.",
        "",
        "| Metric | Result |",
        "|---|---|",
        f"| Spending transactions found (recall) | {pct(total['recall'])} |",
        f"| Extracted rows that are real (precision) | {pct(total['precision'])} |",
        f"| F1 | {pct(total['f1'])} |",
        f"| Date correct | {pct(total['date_accuracy'])} |",
        f"| Spending category correct | {pct(total['category_accuracy'])} |",
        f"| Total spend error | {pct(total['spend_error'])} |",
        "",
        "## Per statement (all runs)",
        "",
        "| Statement | Bank | Rows | Recall | Precision | Category | Spend error |",
        "|---|---|---|---|---|---|---|",
    ]
    for name in [s.name for s in runs[0]]:
        per = summarise([s for s in all_scores if s.name == name])
        lines.append(
            f"| `{name}` | {banks[name]} | {per['true_rows'] // len(runs)} | {pct(per['recall'])} "
            f"| {pct(per['precision'])} | {pct(per['category_accuracy'])} | {pct(per['spend_error'])} |"
        )

    lines += ["", "## Errors", ""]
    any_error = False
    for run_no, run in enumerate(runs, 1):
        for s in run:
            tag = f"run {run_no}, `{s.name}`"
            for t in s.misses:
                any_error = True
                lines.append(f"- {tag} missed: {t['date']} {t['description']} ₹{t['amount']:,.2f}")
            for p in s.extras:
                any_error = True
                lines.append(f"- {tag} extra row: {p.get('date')} {p.get('merchant')} ₹{p.get('amount')}")
            for t, p in s.wrong_category:
                any_error = True
                lines.append(
                    f"- {tag} category: {t['description']} expected `{t['category']}`, got `{p.get('category')}`"
                )
    if not any_error:
        lines.append("None.")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[3])
    parser.add_argument(
        "--runs", type=int, default=1, help="repeat the benchmark to measure run-to-run variance"
    )
    args = parser.parse_args()

    load_dotenv()
    logging.basicConfig(level=logging.WARNING)
    PREDICTIONS.mkdir(exist_ok=True)

    runs: list[list[StatementScore]] = []
    banks: dict[str, str] = {}
    started = time.monotonic()
    for run_no in range(1, args.runs + 1):
        scores: list[StatementScore] = []
        for pdf in sorted(STATEMENTS.glob("*.pdf")):
            truth = json.loads(pdf.with_suffix(".json").read_text())
            predicted = parse_statement(pdf, truth)
            (PREDICTIONS / f"{pdf.stem}.json").write_text(json.dumps(predicted, indent=2) + "\n")
            debits = [t for t in truth["transactions"] if t["transaction_type"] == "debit"]
            spend = [p for p in predicted if p.get("transaction_type") == "debit"]
            score = score_statement(pdf.stem, debits, spend)
            scores.append(score)
            banks[pdf.stem] = truth["bank"]
            print(
                f"run {run_no} {pdf.stem:20s} recall={pct(score.recall):>6s} "
                f"precision={pct(score.precision):>6s} category={pct(score.category_accuracy):>6s}"
            )
        runs.append(scores)

    report = write_report(runs, banks, time.monotonic() - started)
    (EVAL_DIR / "RESULTS.md").write_text(report)
    total = summarise([s for run in runs for s in run])
    print(f"\nOverall F1 {pct(total['f1'])}, category accuracy {pct(total['category_accuracy'])}")
    print(f"Report written to {EVAL_DIR / 'RESULTS.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
